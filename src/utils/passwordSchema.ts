import { z } from "zod";

export const passwordSchema = z
  .string()
  .min(6, "Мінімум 6 символів")
  .regex(/[A-Z]/, "Має містити хоча б одну велику літеру (A-Z)")
  .regex(/[0-9]/, "Має містити хоча б одну цифру (0-9)")
  .regex(
    /[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]/,
    "Має містити хоча б один спеціальний символ (!@#$...)",
  );
